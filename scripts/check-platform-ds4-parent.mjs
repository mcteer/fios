#!/usr/bin/env node
// Compiles actual parent function text with explicit mock types and callees.
import assert from 'node:assert/strict';
import {execFileSync,spawnSync} from 'node:child_process';
import {readFileSync,writeFileSync,mkdtempSync,realpathSync,lstatSync} from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),args=process.argv.slice(2);
assert(process.platform==='darwin'&&process.getuid()>0&&args.length===3&&args[0]==='--isolated'&&args[1]==='--source');
const source=realpathSync(args[2]),info=lstatSync(source);
assert(source.startsWith('/private/tmp/')&&info.uid===process.getuid()&&info.isDirectory()&&(info.mode&0o022)===0);
const directory=mkdtempSync('/private/tmp/fios-ds4-parent-');
const env={PATH:'/usr/bin:/bin',HOME:directory,LANG:'C',LC_ALL:'C',GIT_CONFIG_GLOBAL:'/dev/null',GIT_CONFIG_SYSTEM:'/dev/null',GIT_CONFIG_NOSYSTEM:'1',GIT_NO_REPLACE_OBJECTS:'1'};
const git=(...argv)=>execFileSync('/usr/bin/git',['--no-replace-objects','-c','core.fsmonitor=false','-C',source,...argv],{env,encoding:'utf8',timeout:5000});
const files=['ds4.c','ds4.h','ds4_gpu.h','ds4_gpu_tp.h','ds4_metal.m','ds4_tp.c'];
const patchFile=path.join(root,'platform/studio/native/ds4-9139e2a-participant-retirement.patch'),patch=readFileSync(patchFile,'utf8');
assert.equal(git('rev-parse','HEAD').trim(),'9139e2ae58a41503968a500f36f75895c1ba63fc');
assert.equal(git('diff','HEAD','--name-only').trim(),files.join('\n'));
assert.equal(git('diff','--no-ext-diff','HEAD','--',...files),patch);
const original=readFileSync(path.join(source,'ds4.c'),'utf8');
const start=original.indexOf('int ds4_engine_tp_unbind_checked(ds4_engine *e) {')>=0?original.indexOf('int ds4_engine_tp_unbind_checked(ds4_engine *e) {'):original.indexOf('void ds4_engine_tp_unbind(ds4_engine *e) {');
const end=original.indexOf('\nbool ds4_engine_is_glm_dsa',start);
const close=[...original.matchAll(/^(?:void ds4_engine_close|int ds4_engine_close_checked)\(ds4_engine \*e\) \{[\s\S]*?^\}/gm)].map(m=>m[0]).join('\n');
assert(start>0&&end>start&&close);
const fixtureFile=path.join(root,'platform/studio/Tests/NativeFixtures/DS4Parent.c.fixture'),fixture=readFileSync(fixtureFile,'utf8');
const unit=path.join(directory,'parent.c'),binary=path.join(directory,'parent');
writeFileSync(unit,fixture.replace('/* SOURCE_FUNCTIONS */',original.slice(start,end)+'\n'+close));
execFileSync('/usr/bin/clang',['-std=c11','-O2','-UNDEBUG',unit,'-o',binary],{env,timeout:30000});
const preparationResults=['--gpu-unbind','--gpu-close','--gpu-empty','--prepared-success','--cpu-close','--cpu-empty','--checked-refusal','--child-uncertain','--selected-active','--pagein-active','--cpu-unbind'].map(mode=>{
 const r=spawnSync(binary,[mode],{env,encoding:'utf8',timeout:5000});
 writeFileSync(path.join(directory,mode+'-stderr.log'),r.stderr??'');return r;
});
const closeResult=spawnSync(binary,['--close'],{env,encoding:'utf8',timeout:5000});
writeFileSync(path.join(directory,'close-stderr.log'),closeResult.stderr??'');
const emptyResult=spawnSync(binary,['--empty'],{env,encoding:'utf8',timeout:5000});
writeFileSync(path.join(directory,'empty-stderr.log'),emptyResult.stderr??'');
console.log('Parent fixture state:',directory);
const result=spawnSync(binary,[],{env,encoding:'utf8',timeout:5000});
writeFileSync(path.join(directory,'stderr.log'),result.stderr??'');
assert(!result.error&&!result.signal,'Parent fixture crash/deadline is not acceptance');assert.equal(result.status,0,result.stderr);
assert(!closeResult.error&&!closeResult.signal,'Parent close fixture crash/deadline is not acceptance');assert.equal(closeResult.status,0,closeResult.stderr);
assert(!emptyResult.error&&!emptyResult.signal,'Empty parent fixture crash/deadline is not acceptance');assert.equal(emptyResult.status,0,emptyResult.stderr);
for(const r of preparationResults){assert(!r.error&&!r.signal,'Preparation refusal fixture crash/deadline is not acceptance');assert.equal(r.status,0,r.stderr);}
const pageinGuard=' || metal_graph_stream_pagein_busy()';assert.equal(close.split(pageinGuard).length,2);
const mutationUnit=path.join(directory,'parent-pagein-guard-omission.c'),mutationBinary=path.join(directory,'parent-pagein-guard-omission');
writeFileSync(mutationUnit,fixture.replace('/* SOURCE_FUNCTIONS */',original.slice(start,end)+'\n'+close.replace(pageinGuard,'')));
execFileSync('/usr/bin/clang',['-std=c11','-O2','-UNDEBUG',mutationUnit,'-o',mutationBinary],{env,timeout:30000});
const mutation=spawnSync(mutationBinary,['--pagein-active'],{env,encoding:'utf8',timeout:5000});
writeFileSync(path.join(directory,'pagein-guard-omission-stderr.log'),mutation.stderr??'');
assert(!mutation.error&&!mutation.signal);assert.equal(mutation.status,77);assert(mutation.stderr.includes('FIO_DS4_ENGINE_RELEASED_WITH_PAGEIN_CUSTODY'));
assert.equal(readFileSync(path.join(source,'ds4.c'),'utf8'),original);assert.equal(readFileSync(fixtureFile,'utf8'),fixture);assert.equal(readFileSync(patchFile,'utf8'),patch);assert.equal(git('diff','--no-ext-diff','HEAD','--',...files),patch);
console.log(result.stdout.trim());
console.log(JSON.stringify({directory,source_sha256:createHash('sha256').update(original).digest('hex'),fixture_sha256:createHash('sha256').update(fixture).digest('hex'),source_control_flow_only:true,native_abi:false,native_authority:false}));
