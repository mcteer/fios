#!/usr/bin/env node
// Private dependency recomposition, never installation or native authority.
import assert from 'node:assert/strict';
import {readFileSync,lstatSync,realpathSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {verifyNativeReview,stageNativeReview,finishNativeReview} from './lib/platform-native-review.mjs';
import {parseMlxSourceReview,verifyMlxSourceReview} from './lib/platform-mlx-source-review.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const a=process.argv.slice(2);
assert(a.length===15&&a[0]==='--isolated');
for(const [i,key]of ['--base','--sha256','--previous-sdk','--sdk','--sdk-sha256','--source','--output'].entries())assert.equal(a[1+i*2],key);
for(const i of [2,6,8,12,14])assert(path.isAbsolute(a[i]));
const sha=b=>createHash('sha256').update(b).digest('hex');
const base=verifyNativeReview(a[2],a[4]),inputs=base.receipt.declared_inputs;
assert(inputs.source_component_diagnostics===true&&inputs.mlx_source_dependency);
assert.equal(inputs.root_patch_sha256,sha(readFileSync(path.join(root,'platform/studio/native/mlx-serve-26.10.3.patch'))));
assert.equal(inputs.mlx_participant_source_sha256,sha(readFileSync(path.join(root,'platform/studio/native/source_mlx_participants.cpp'))));
const previousStat=lstatSync(a[6]);
assert(realpathSync(a[6])===a[6]&&previousStat.isFile()&&!previousStat.isSymbolicLink()&&previousStat.nlink===1&&previousStat.uid===process.getuid()&&(previousStat.mode&0o222)===0&&previousStat.size>0&&previousStat.size<=(1<<20));
const oldBytes=readFileSync(a[6]);
const old=parseMlxSourceReview(oldBytes,inputs.mlx_source_dependency.receipt_sha256);
assert.deepEqual(old.files,inputs.mlx_source_dependency.library_inputs);
const dependency=verifyMlxSourceReview(a[8],a[10],a[12]);
const next=parseMlxSourceReview(readFileSync(a[8]),a[10]);
for(const key of ['pins','features','sdk','loader_fixture_sha256'])assert.deepEqual(next[key],old[key]);
for(const [name,digest]of Object.entries(old.declared_sources))if(name.endsWith('.h'))assert.equal(next.declared_sources[name],digest,'Public ABI headers changed; rebuild required');
const libraries=Object.fromEntries(Object.keys(old.files).map(name=>[name,dependency.libraries[name]]));
for(const name of ['libmlxc.dylib','libwebp.dylib','libsharpyuv.dylib','libllama.dylib'])libraries[name]=path.join(base.directory,'Frameworks',name);
const review=stageNativeReview({directory:a[14],binary:base.binary,libraries,inputs:{...inputs,mlx_source_dependency:dependency,dependency_composition:{base_receipt_sha256:a[4],binary_rebuilt:false,source_abi_headers_unchanged:true}}});
const log=execFileSync(process.execPath,[path.join(root,'scripts/check-platform-native-http.mjs'),'--isolated','--binary',review.binary,'--sha256',review.sha256],{encoding:'utf8',timeout:180000,maxBuffer:8<<20});
assert(log.includes('SOURCE_COMPONENT_PROVIDER_AVAILABLE'));
assert.deepEqual(verifyNativeReview(a[2],a[4]),base);
assert.deepEqual(verifyMlxSourceReview(a[8],a[10],a[12]),dependency);
assert(readFileSync(a[6]).equals(oldBytes));
console.log(log);
console.log(JSON.stringify({...finishNativeReview(review),binary_rebuilt:false,root_tests_rerun:false,coverage:'unknown',native_admission_authority:false}));
